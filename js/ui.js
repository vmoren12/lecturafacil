/** Opens a <dialog> with the given HTML; resolves with the dialog's returnValue. */
export function dialog(html, { wide = false, onOpen } = {}) {
  const d = document.createElement("dialog");
  d.className = "dlg" + (wide ? " wide" : "");
  d.innerHTML = html;
  document.body.appendChild(d);
  return new Promise(resolve => {
    d.addEventListener("close", () => { resolve(d.returnValue); d.remove(); });
    d.addEventListener("click", e => {
      if (e.target === d) d.close("cancel"); // click on the backdrop
      const c = e.target.closest("[data-close]");
      if (c) d.close(c.dataset.close || "cancel");
    });
    d.showModal();
    if (onOpen) onOpen(d);
  });
}

/** Downloads a JSON object as a file. */
export function downloadJSON(obj, filename) {
  downloadText(JSON.stringify(obj), filename, "application/json");
}

/** Downloads text as a file. */
export function downloadText(text, filename, type = "text/plain;charset=utf-8") {
  const blob = new Blob([text], { type });
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob);
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  setTimeout(() => { URL.revokeObjectURL(a.href); a.remove(); }, 1000);
}

export const slug = s => normalizeSlug(s) || "llibre";
function normalizeSlug(s) {
  return String(s).normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 60);
}

export async function copyText(text) {
  try { await navigator.clipboard.writeText(text); return true; } catch { return false; }
}
